import { test, expect } from '@playwright/test';
import { resources } from '../../apps/web/src/i18n';
import { enterAccounts } from './helpers/vault-access';
import { importVisualKdbxEntries } from './fixtures/password-smart-import-visual';

for (const language of ['zh-CN', 'en'] as const) test(`${language} account search lists every matching platform member and clearing restores the default`, async ({ browser }, info) => {
 const t = (key: string) => (resources[language].translation as Record<string,string>)[key] ?? key;
 const context = await browser.newContext({ baseURL: info.project.use.baseURL, viewport: { width: 1280, height: 900 } });
 await context.addInitScript(lang => localStorage.setItem('keepany-language', lang), language);
 const page = await context.newPage(), master = 'SyntheticPlatformSearch2026!';
 const cards = page.locator('.compact-account-card');
 const save = async () => { await page.getByRole('dialog').getByRole('button', { name: /^(保存|Save|保存条目|Save entry)$/ }).click(); await expect(page.getByRole('dialog')).toHaveCount(0); };
 try {
  await page.goto('/accounts'); await enterAccounts(page, language, master);
  await page.locator('.asset-category-toolbar').getByRole('button', { name: t('add'), exact: true }).click();
  await page.locator('#password-vault-entry-title').fill('QQ personal');
  await page.locator('#password-vault-entry-username').fill('personal-a@example.test');
  await page.locator('#password-vault-entry-password').fill('SyntheticPersonalPassword!');
  await page.getByRole('dialog').getByRole('button', { name: t('pwVaultAddIdentifier'), exact: true }).click();
  await page.locator('.pw-smart-identifier-row input').last().fill('QQ-alias-a');
  await save();
  const personalId = await cards.getAttribute('data-account-id');
  await cards.getByRole('button', { name: t('add'), exact: true }).click();
  await page.locator('#password-vault-entry-title').fill('QQ work');
  await page.locator('#password-vault-entry-username').fill('work-b@example.test');
  await page.locator('#password-vault-entry-password').fill('SyntheticWorkPassword!');
  await save(); await expect(cards).toHaveCount(1);
  if (await cards.locator('[data-login-username]').innerText() !== 'work-b@example.test') await cards.locator('[data-account-switch]').click();
  await cards.locator('.compact-account-title-block').click();
  const setDefault = page.locator('[data-account-default]');
  if (await setDefault.isEnabled()) await setDefault.click();
  await expect(setDefault).toHaveAttribute('aria-pressed', 'true');
  await expect(setDefault).toBeDisabled();
  await page.getByRole('link', { name: t('accountBack'), exact: true }).click();
  await expect(cards).toHaveCount(1); await expect(cards.locator('[data-login-username]')).toHaveText('work-b@example.test');
  const workId = await cards.getAttribute('data-account-id');
  await importVisualKdbxEntries(page, t, [{ title: 'QQ private', username: 'private-c@example.test', password: 'SyntheticPrivatePassword!', templateSourceId: `card:${personalId}` }]);
  await expect(cards).toHaveCount(1); await expect(cards).toHaveAttribute('data-account-id', workId!);
  const search = page.locator('#password-vault-search-input');
  await search.fill('personal-a');
  await expect(cards).toHaveCount(1); await expect(cards).toHaveAttribute('data-account-id', personalId!);
  await expect(cards.locator('[data-login-username]')).toHaveText('personal-a@example.test');
  await expect(cards.locator('[data-account-switch]')).toBeDisabled();
  await cards.getByRole('button', { name: t('edit'), exact: true }).click();
  await expect(page.locator('#password-vault-entry-username')).toHaveValue('personal-a@example.test');
  await page.getByRole('dialog').getByRole('button', { name: t('cancel'), exact: true }).click();
  await cards.locator('.compact-account-title-block').click();
  await expect(page.locator('.account-login-summary [data-login-username]')).toHaveText('personal-a@example.test');
  await page.getByRole('link', { name: t('accountBack'), exact: true }).click();
  await search.fill('QQ');
  await expect(cards).toHaveCount(3);
  expect((await cards.locator('[data-login-username]').allTextContents()).sort()).toEqual(['personal-a@example.test', 'private-c@example.test', 'work-b@example.test']);
  await expect(cards.locator('[data-account-switch]')).toHaveCount(3);
  for (const control of await cards.locator('[data-account-switch]').all()) await expect(control).toBeDisabled();
  await page.screenshot({ path: info.outputPath('QQ-expanded-1280.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 900 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth > innerWidth)).toBe(false);
  await page.screenshot({ path: info.outputPath('QQ-expanded-390.png'), fullPage: true });
  await page.setViewportSize({ width: 1280, height: 900 });
  await cards.filter({ hasText: 'QQ private' }).locator('.compact-account-title-block').click();
  await expect(page).toHaveURL(/#login-detail-/);
  await expect(page.locator('.account-login-summary [data-login-username]')).toHaveText('private-c@example.test');
  await page.getByRole('link', { name: t('accountBack'), exact: true }).click();
  await search.fill('QQ-alias-a');
  await expect(cards).toHaveCount(1); await expect(cards).toHaveAttribute('data-account-id', personalId!);
  await expect(cards.locator('[data-login-username]')).toHaveText('QQ-alias-a');
  await search.fill('  ');
  await expect(cards).toHaveCount(1); await expect(cards).toHaveAttribute('data-account-id', workId!);
  await expect(cards.locator('[data-login-username]')).toHaveText('work-b@example.test');
  await search.fill('QQ'); await expect(cards).toHaveCount(3);
  await page.getByRole('button', { name: t('accountListClearSearch'), exact: true }).click();
  await expect(cards).toHaveCount(1); await expect(cards).toHaveAttribute('data-account-id', workId!);
  await page.reload(); await enterAccounts(page, language, master);
  await expect(cards).toHaveCount(1); await expect(cards).toHaveAttribute('data-account-id', workId!);
 } finally { await context.close(); }
});
