async function prepare(context: BrowserContext, locale: Locale, width = 1280) {
	await context.addInitScript(value => localStorage.setItem("keepany-language", value), locale);
	const page = await context.newPage();
	await page.setViewportSize({ width, height: 1000 });
	await page.clock.setFixedTime(new Date(assetFixtureTime));
	const sourceRequests = recordDevelopmentRequests(context);
	const errors: string[] = [];
	page.on("pageerror", error => errors.push(error.message));
	return { page, errors, sourceRequests };
}

async function restore(page: Page) {
	await page.goto("/intake");
	await restoreCompletionArchive(page, assetFixturePassword, fixture.archive);
	await page.goto("/assets");
	await expect(page.locator(".assets-workbench")).toBeVisible();
}

async function noOverflow(page: Page) {
	expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
}

async function capture(page: Page, name: string, fullPage = true) {
	await noOverflow(page);
	await page.screenshot({ path: join(evidence, `${name}.png`), fullPage, animations: "disabled" });
}

async function expectUnobscuredFinanceError(page: Page) {
	const alert = page.getByRole("dialog").getByRole("alert");
	await expect(alert).toBeVisible();
	await expect(alert).toBeInViewport({ ratio: 1 });
	await expect.poll(() => alert.evaluate(node => {
		const popup = node.closest('[role="dialog"]');
		const actions = node.closest("form")?.querySelector(":scope > .actions");
		if (!popup || !actions) return false;
		const errorBox = node.getBoundingClientRect(), popupBox = popup.getBoundingClientRect(), actionBox = actions.getBoundingClientRect();
		return errorBox.width > 0 && errorBox.height > 0 && errorBox.top >= Math.max(0, popupBox.top) &&
			errorBox.bottom <= Math.min(innerHeight, popupBox.bottom) && errorBox.bottom <= actionBox.top + 1;
	})).toBe(true);
}

