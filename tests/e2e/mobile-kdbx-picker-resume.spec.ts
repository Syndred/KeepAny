import { readFile } from 'node:fs/promises';
import { expect, test } from '@playwright/test';
import { resources } from '../../apps/web/src/i18n';
import { sourceModuleUrl } from './helpers/source-module-url';

test.use({ viewport: { width: 390, height: 844 } });
for (const language of ['en', 'zh-CN'] as const) test(`encrypted KDBX selection survives background locking and requires fresh passwords in ${language}`, async ({ page }, info) => {
  test.setTimeout(90_000);
  const labels = resources[language].translation, t = (key: string) => String(labels[key]);
  const master = 'Synthetic-picker-master-2026!', entryName = 'Synthetic picker protected entry';
  await page.addInitScript(value => localStorage.setItem('keepany-language', value), language);
  await page.goto('/assets/vault');
  await page.locator('#password-vault-master').fill(master);
  await page.locator('#password-vault-master-confirm').fill(master);
  await page.getByRole('button', { name: t('pwVaultCreate'), exact: true }).click();
  await expect(page.locator('.password-vault-toolbar')).toBeVisible();
  await page.getByRole('button', { name: t('pwVaultNewEntry'), exact: true }).click();
  await page.locator('#password-vault-entry-title').fill(entryName);
  await page.locator('#password-vault-entry-password').fill('Synthetic-picker-entry-secret');
  await page.getByRole('dialog').getByRole('button', { name: t('pwVaultSaveEntry'), exact: true }).click();
  await expect(page.getByRole('dialog')).toBeHidden();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: t('pwVaultExport'), exact: true }).click();
  const path = await (await download).path();
  if (!path) throw Error('missing-synthetic-kdbx-download');
  const ciphertext = await readFile(path);
  const read = () => page.evaluate(async modulePath => {
    const { localRepository } = await import(/* @vite-ignore */ modulePath);
    const record = await (await localRepository()).readPasswordVault();
    return record ? { revision: record.revision, bytes: Array.from(record.bytes as Uint8Array) } : null;
  }, sourceModuleUrl('packages/local-db/src/index.ts'));
  const before = await read();
  await page.getByRole('button', { name: t('pwVaultImport'), exact: true }).click();
  const file = page.locator('#password-vault-import-file');
  const input = await file.elementHandle();
  await page.locator('#password-vault-import-password').fill('Synthetic-unsubmitted-backup-secret');
  // B/C lifecycle injection. The separate Android run uses the actual OS picker.
  await page.evaluate(() => dispatchEvent(new Event('keepany-native-background')));
  await expect(page.getByText(t('pwVaultImportUnlockToContinue'), { exact: true })).toBeVisible();
  expect(await input?.evaluate(node => node.isConnected)).toBe(true);
  await expect(page.locator('#password-vault-import-password')).toHaveValue('');
  await expect(page.getByText(entryName, { exact: true })).toHaveCount(0);
  await file.setInputFiles({ name: 'synthetic-selected.kdbx', mimeType: 'application/octet-stream', buffer: ciphertext });
  expect(await read()).toEqual(before);
  await page.screenshot({ path: info.outputPath(`locked-import-${language}-390.png`), fullPage: false });
  await page.locator('#password-vault-unlock-master').fill(master);
  await page.getByRole('dialog').getByRole('button', { name: t('pwVaultUnlock'), exact: true }).click();
  await expect(page.locator('#password-vault-import-password')).toBeVisible();
  await expect(page.locator('#password-vault-import-password')).toHaveValue('');
  expect(await file.evaluate(node => (node as HTMLInputElement).files?.[0]?.name)).toBe('synthetic-selected.kdbx');
  await page.locator('#password-vault-import-password').fill(master);
  await page.getByRole('dialog').getByRole('button', { name: t('pwVaultImportNow'), exact: true }).click();
  await expect(page.getByRole('dialog')).toBeHidden();
  await expect(page.locator('.password-vault-entry-list .password-vault-entry')).toHaveCount(1);
  const after = await read();
  await page.getByRole('button', { name: t('pwVaultImport'), exact: true }).click();
  await page.evaluate(() => dispatchEvent(new Event('keepany-native-background')));
  await expect(page.getByText(t('pwVaultImportUnlockToContinue'), { exact: true })).toBeVisible();
  await page.getByRole('dialog').getByRole('button', { name: t('cancel'), exact: true }).click();
  await expect(page.getByRole('dialog')).toBeHidden();
  expect(await read()).toEqual(after);
});
